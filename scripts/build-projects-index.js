#!/usr/bin/env node
/**
 * Build js/projects-index.js — slim card/fit fields for homepage (<32KB).
 * Source of truth remains js/projects-data.js (full case studies).
 */
'use strict';

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'js', 'projects-data.js');
const OUT = path.join(ROOT, 'js', 'projects-index.js');

const sandbox = { window: {}, console };
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(SRC, 'utf8'), sandbox, { filename: 'projects-data.js' });

const projects = sandbox.window.HASH_PROJECTS || sandbox.HASH_PROJECTS || [];
if (!projects.length) {
  console.error('No HASH_PROJECTS from projects-data.js');
  process.exit(1);
}

const slim = projects.map(function (p) {
  const images = p.images || {};
  return {
    slug: p.slug,
    name: p.name,
    title: p.title || '',
    lead: p.lead || '',
    industry: p.industry || '',
    services: p.services || '',
    role: p.role || '',
    href: p.href || '/project/' + encodeURIComponent(p.slug) + '/',
    featured: !!p.featured,
    homeOrder: typeof p.homeOrder === 'number' ? p.homeOrder : null,
    cardTone: p.cardTone || 'navy',
    tags: Array.isArray(p.tags) ? p.tags.slice(0, 4) : [],
    earlyMetrics: Array.isArray(p.earlyMetrics)
      ? p.earlyMetrics.slice(0, 3).map(function (m) {
          return { value: m.value || '', label: m.label || '' };
        })
      : [],
    images: {
      hero: images.hero || '',
      pixel: images.pixel || ''
    }
  };
});

const body =
  '/**\n' +
  ' * Generated by scripts/build-projects-index.js — do not edit by hand.\n' +
  ' * Slim listing for homepage + Service Fit. Full case data: projects-data.js\n' +
  ' */\n' +
  '(function (global) {\n' +
  "  'use strict';\n" +
  '  var PROJECTS = ' +
  JSON.stringify(slim) +
  ';\n' +
  '  global.HASH_PROJECTS = PROJECTS;\n' +
  '  global.HASH_PROJECTS_BY_SLUG = PROJECTS.reduce(function (acc, project) {\n' +
  '    acc[project.slug] = project;\n' +
  '    return acc;\n' +
  '  }, {});\n' +
  '  global.HASH_PROJECTS_INDEX = true;\n' +
  '})(typeof window !== "undefined" ? window : this);\n';

fs.writeFileSync(OUT, body, 'utf8');
const bytes = Buffer.byteLength(body, 'utf8');
console.log(
  'Wrote',
  path.relative(ROOT, OUT),
  '(' + bytes + ' bytes,',
  slim.length,
  'projects)'
);
