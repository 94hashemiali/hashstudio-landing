def write_articles_index(articles: dict[str, dict[str, Any]]) -> Path:
    index = {slug: listing_fields(article) for slug, article in articles.items()}
    # Stable key order
    ordered = {slug: index[slug] for slug in sorted(index)}
    payload = json.dumps(ordered, ensure_ascii=False, indent=2)
    default = "digital-product-guide" if "digital-product-guide" in ordered else next(iter(ordered))
    content = f"""/* Generated by scripts/build-content.py — listing fields only.
 * Source of truth: js/articles-data.js
 * Do not edit by hand.
 */
(function (global) {{
  'use strict';
  var BY_SLUG = {payload};
  global.HASH_ARTICLES_BY_SLUG = BY_SLUG;
  global.HASH_ARTICLE_DEFAULT = BY_SLUG['{default}'];
}})(typeof window !== 'undefined' ? window : this);
"""
    out = ROOT / "js/articles-index.js"
    out.write_text(content, encoding="utf-8")
    return out


def main() -> int:
    articles = load_articles()
    graph = load_article_graph()
    projects = load_project_cards()

    if not graph:
        print("BUILD FAILED — content-graph ARTICLES parse returned empty")
        return 1
    missing_graph = sorted(set(articles) - set(graph))
    if missing_graph:
        print("BUILD FAILED — articles missing content-graph entries:")
        for slug in missing_graph:
            print(f"ERROR: {slug}")
        return 1

    errors = validate_articles(articles, graph, projects)
    if errors:
        print("BUILD FAILED — validation errors:")
        for err in errors:
            print(f"ERROR: {err}")
        return 1

    article_root = ROOT / "article"
    article_root.mkdir(exist_ok=True)

    # Remove obsolete generated article dirs not in data
    existing = {p.name for p in article_root.iterdir() if p.is_dir()} if article_root.exists() else set()
    for stale in sorted(existing - set(articles)):
        stale_index = article_root / stale / "index.html"
        if stale_index.exists() and "Generated by scripts/build-content.py" in stale_index.read_text(
            encoding="utf-8", errors="ignore"
        ):
            stale_index.unlink()
            try:
                (article_root / stale).rmdir()
            except OSError:
                pass
            print(f"Removed stale article/{stale}/")

    for slug, article in sorted(articles.items()):
        rel = graph.get(slug) or {
            "projects": [],
            "services": [],
            "ctaTitle": "",
            "ctaBody": "",
        }
        html = render_article(article, rel, projects)
        out_dir = article_root / slug
        out_dir.mkdir(parents=True, exist_ok=True)
        (out_dir / "index.html").write_text(html, encoding="utf-8")

    index_path = write_articles_index(articles)
    print(f"Generated {len(articles)} article pages → article/<slug>/index.html")
    print(f"Generated {index_path.relative_to(ROOT)}")
    return 0


