def validate_articles(
    articles: dict[str, dict[str, Any]],
    graph: dict[str, dict[str, Any]],
    projects: dict[str, dict[str, str]],
) -> list[str]:
    errors: list[str] = []
    service_dirs = {p.name for p in (ROOT / "service").iterdir() if p.is_dir()}

    for slug, article in articles.items():
        if article.get("slug") != slug:
            errors.append(f'Article "{slug}": slug field mismatch')
        for field in ("title", "lead", "hero", "author", "sections", "blocks", "date", "read", "tag"):
            if not article.get(field):
                errors.append(f'Article "{slug}": missing required field {field}')
        author = article.get("author") or {}
        for field in ("name", "role", "avatar", "bio", "aboutTitle"):
            if not author.get(field):
                errors.append(f'Article "{slug}": missing author.{field}')

        for rel in article.get("related") or []:
            rslug = rel.get("slug")
            if rslug and rslug not in articles:
                errors.append(f'Article "{slug}": related points to missing article "{rslug}"')
            img = rel.get("image")
            path = local_asset_path(img or "")
            if path and not path.is_file():
                errors.append(
                    f'Article "{slug}" related "{rslug}" references missing asset:\n  {img}'
                )

        for key in ("hero", "inline"):
            ref = article.get(key)
            path = local_asset_path(ref or "")
            if ref and path and not path.is_file():
                errors.append(f'Article "{slug}" references missing asset:\n  {ref}')

        avatar = (article.get("author") or {}).get("avatar")
        path = local_asset_path(avatar or "")
        if avatar and path and not path.is_file():
            errors.append(f'Article "{slug}" references missing author avatar:\n  {avatar}')

        rel = graph.get(slug) or {}
        for pslug in rel.get("projects") or []:
            if pslug not in projects:
                errors.append(f'Article "{slug}": content-graph project missing: {pslug}')
            else:
                hero = projects[pslug]["hero"]
                path = local_asset_path(hero)
                if path and not path.is_file():
                    errors.append(
                        f'Article "{slug}" related project "{pslug}" missing asset:\n  {hero}'
                    )
        for sslug in rel.get("services") or []:
            if sslug not in service_dirs:
                errors.append(f'Article "{slug}": content-graph service missing: {sslug}')

    return errors


def render_body(article: dict[str, Any]) -> str:
    parts: list[str] = []
    blocks = article.get("blocks") or []
    for i, block in enumerate(blocks):
        parts.append(f'<section class="article-section" id="{escape_html(block["id"])}">')
        parts.append(
            f'<h2 class="article-section__heading">{escape_html(block.get("heading", ""))}</h2>'
        )
        for p in block.get("paragraphs") or []:
            parts.append(f'<p class="article-section__p">{escape_html(p)}</p>')
        if block.get("listTitle"):
            parts.append(
                f'<h3 class="article-section__sub">{escape_html(block["listTitle"])}</h3>'
            )
        if block.get("list"):
            items = "".join(f"<li>{escape_html(item)}</li>" for item in block["list"])
            parts.append(f'<ul class="article-list">{items}</ul>')
        if block.get("showInline") and article.get("inline"):
            caption = escape_html(article.get("inlineCaption") or "")
            parts.append(
                '<figure class="article-figure">'
                f'<img src="{escape_html(article["inline"])}" alt="{caption}" '
                'width="759" height="379" loading="lazy" decoding="async">'
                f"<figcaption>{caption}</figcaption>"
                "</figure>"
            )
        if block.get("showTip") and article.get("tip"):
            tip = article["tip"]
            parts.append(
                '<aside class="article-tip">'
                '<div class="article-tip__head">'
                '<img src="assets/icons/article/info.svg" alt="" width="18" height="18">'
                f"<strong>{escape_html(tip.get('title', ''))}</strong></div>"
                f"<p>{escape_html(tip.get('body', ''))}</p></aside>"
            )
        parts.append("</section>")
        if i == 0 and article.get("quote") and article["quote"].get("text"):
            q = article["quote"]
            parts.append(
                '<blockquote class="article-quote">'
                f'<p class="article-quote__text">{escape_html(q["text"])}</p>'
                f'<cite class="article-quote__cite">— {escape_html(q.get("cite", ""))}</cite>'
                "</blockquote>"
            )
    if article.get("closing"):
        parts.append(
            f'<p class="article-section__p article-section__p--closing">'
            f'{escape_html(article["closing"])}</p>'
        )
    return "\n            ".join(parts)


def render_toc(article: dict[str, Any]) -> str:
    items = []
    for index, section in enumerate(article.get("sections") or []):
        active = " is-active" if index == 0 else ""
        items.append(
            f'<li><a class="article-toc__link{active}" href="#{escape_html(section["id"])}">'
            f'{escape_html(section["label"])}</a></li>'
        )
    return "\n              ".join(items)


def render_related(article: dict[str, Any]) -> str:
    cards = []
    for post in article.get("related") or []:
        cards.append(
            f'<a class="article-related__card" href="/article/{escape_html(post["slug"])}/" '
            f'data-cta="view-article" data-cta-location="article-related" '
            f'data-content-slug="{escape_html(post["slug"])}">'
            f'<div class="article-related__media">'
            f'<img src="{escape_html(post.get("image", ""))}" '
            f'alt="{escape_html(post.get("title", ""))}" '
            'width="384" height="240" loading="lazy" decoding="async"></div>'
            f'<div class="article-related__body">'
            f'<span class="article-related__tag">{escape_html(post.get("tag", ""))}</span>'
            f'<h3 class="article-related__title">{escape_html(post.get("title", ""))}</h3>'
            f'<div class="article-related__meta"><time>{escape_html(post.get("date", ""))}</time>'
            f'<span>زمان مطالعه: {escape_html(post.get("read", ""))}</span></div>'
            f"</div></a>"
        )
    return "\n          ".join(cards)


def render_projects(
    article: dict[str, Any],
    rel: dict[str, Any],
    projects: dict[str, dict[str, str]],
) -> tuple[str, bool]:
    cards = []
    for pslug in rel.get("projects") or []:
        p = projects.get(pslug)
        if not p:
            continue
        cards.append(
            f'<a class="article-proof__card" href="/project/{escape_html(p["slug"])}/" '
            f'data-cta="content-bridge" data-cta-location="article-bridge" '
            f'data-from-type="article" data-from-slug="{escape_html(article["slug"])}" '
            f'data-to-type="project" data-to-slug="{escape_html(p["slug"])}" '
            f'data-content-slug="{escape_html(article["slug"])}" '
            f'data-project-slug="{escape_html(p["slug"])}">'
            f'<figure class="article-proof__media">'
            f'<img src="{escape_html(p["hero"])}" alt="{escape_html(p["name"])}" '
            'width="640" height="400" loading="lazy" decoding="async"></figure>'
            f'<div class="article-proof__body">'
            f'<span class="article-proof__industry">{escape_html(p["industry"])}</span>'
            f'<h3 class="article-proof__title">{escape_html(p["name"])}</h3>'
            f'<p class="article-proof__meta">{escape_html(p["services"])}</p>'
            f'<p class="article-proof__lead">{escape_html(p["lead"])}</p>'
            f'<span class="article-proof__cta">مطالعه کیس‌استادی {escape_html(p["name"])}</span></div></a>'
        )
    return "\n          ".join(cards), bool(cards)


def render_services(article: dict[str, Any], rel: dict[str, Any]) -> tuple[str, bool]:
    cards = []
    for sslug in rel.get("services") or []:
        label = SERVICE_LABELS.get(sslug, sslug)
        cards.append(
            f'<a class="article-service-link" href="/service/{escape_html(sslug)}/" '
            f'data-cta="content-bridge" data-cta-location="article-bridge" '
            f'data-from-type="article" data-from-slug="{escape_html(article["slug"])}" '
            f'data-to-type="service" data-to-slug="{escape_html(sslug)}" '
            f'data-content-slug="{escape_html(article["slug"])}" '
            f'data-service-slug="{escape_html(sslug)}">آشنایی با خدمت {escape_html(label)}</a>'
        )
    return "\n            ".join(cards), bool(cards)


def render_solutions(article: dict[str, Any], rel: dict[str, Any]) -> tuple[str, bool]:
    labels = load_solution_labels()
    cards = []
    for sslug in (rel.get("solutions") or [])[:2]:
        label = labels.get(sslug, sslug)
        cards.append(
            f'<a class="article-service-link article-service-link--solution" '
            f'href="/solutions/{escape_html(sslug)}/" '
            f'data-cta="content-bridge" data-cta-location="article-bridge" '
            f'data-from-type="article" data-from-slug="{escape_html(article["slug"])}" '
            f'data-to-type="solution" data-to-slug="{escape_html(sslug)}" '
            f'data-content-slug="{escape_html(article["slug"])}">'
            f'بررسی مسیر {escape_html(label)}</a>'
        )
    return "\n            ".join(cards), bool(cards)


def json_ld(article: dict[str, Any], canonical: str, page_desc: str, og_image: str) -> str:
    graph = [
        {
            "@type": "BlogPosting",
            "headline": article["title"],
            "description": page_desc,
            "url": canonical,
            "image": og_image,
            "inLanguage": "fa-IR",
            "mainEntityOfPage": {"@type": "WebPage", "@id": canonical},
            "author": {
                "@type": "Person",
                "name": (article.get("author") or {}).get("name") or "استودیو هش",
            },
            "publisher": {
                "@type": "Organization",
                "name": "استودیو هش",
                "url": f"{BASE}/",
                "logo": {
                    "@type": "ImageObject",
                    "url": abs_url("assets/images/home/logo.png"),
                },
            },
        },
        {
            "@type": "BreadcrumbList",
            "itemListElement": [
                {
                    "@type": "ListItem",
                    "position": 1,
                    "name": "خانه",
                    "item": f"{BASE}/",
                },
                {
                    "@type": "ListItem",
                    "position": 2,
                    "name": "مقالات",
                    "item": f"{BASE}/blog.html",
                },
                {
                    "@type": "ListItem",
                    "position": 3,
                    "name": article["title"],
                    "item": canonical,
                },
            ],
        },
    ]
    payload = {"@context": "https://schema.org", "@graph": graph}
    return json.dumps(payload, ensure_ascii=False, separators=(",", ":"))


